"""Build this sketch's generated vocabulary tables from its tokenizer.

Writes generated/vocab.h: token id -> raw UTF-8 bytes, so the device just
Serial.write()s the bytes of each generated token (llama2.c style). Also prints
the token ids for the demo prompt the sketch is primed with.

This table decodes generated token ids.  The companion
generate_tokenizer_header.py builds the encoder used for typed prompts.
"""

import argparse
from pathlib import Path

from tokenizers import Tokenizer

SKETCH = Path(__file__).resolve().parent.parent
ROOT = SKETCH.parent.parent
DEFAULT_TOK = ROOT / "artifacts" / "tokenizer.json"
DEFAULT_OUT = SKETCH / "generated" / "vocab.h"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tokenizer", default=DEFAULT_TOK,
                    help="canonical tokenizer.json the header is built from")
    ap.add_argument("--out", default=DEFAULT_OUT, help="header to write")
    args = ap.parse_args()
    TOK, OUT = args.tokenizer, args.out

    tok = Tokenizer.from_file(str(TOK))  # rejects PathLike
    V = tok.get_vocab_size()
    eot = tok.token_to_id("<|endoftext|>")
    if eot is None:
        raise SystemExit("tokenizer has no <|endoftext|> token")

    # Raw UTF-8 bytes per token: decode single-id sequences. Concatenating the
    # pieces reconstructs Portuguese text without a Unicode conversion on ESP32.
    blob = bytearray()
    offs = [0]
    for i in range(V):
        s = tok.decode([i])
        blob.extend(s.encode("utf-8"))
        offs.append(len(blob))

    # The output directory may not exist in a fresh clone.
    Path(OUT).parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by firmware/historinhas/tools/generate_vocab.py\n"
                "// token id -> raw UTF-8 bytes.\n")
        f.write("#ifndef VOCAB_H\n#define VOCAB_H\n")
        f.write(f"#define VOCAB_N {V}\n")
        f.write(f"#define VOCAB_EOT {eot}\n")
        f.write(f"static const unsigned char VOCAB_BLOB[{len(blob)}] = {{\n")
        for i in range(0, len(blob), 20):
            f.write("  " + ",".join(str(b) for b in blob[i:i+20]) + ",\n")
        f.write("};\n")
        f.write(f"static const int VOCAB_OFF[{len(offs)}] = {{\n")
        for i in range(0, len(offs), 20):
            f.write("  " + ",".join(str(o) for o in offs[i:i+20]) + ",\n")
        f.write("};\n#endif\n")

    print(f"wrote {OUT}: {V} tokens, blob {len(blob)/1024:.0f} KB")



if __name__ == "__main__":
    main()
